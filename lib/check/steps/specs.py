#!/usr/bin/env python3
"""Fails a spec or plan whose front matter breaks its schema, or whose body breaks the spec format.

  - every `specs/core/*.md`, TEMPLATE.md included, has front matter that validates against specs/schema/spec.yaml.
  - a spec's `id` is its file name, it has the `# ` title and the headings in REQUIRED_HEADINGS, and each requirement
    line (`- **BAR-01** ...`) carries the id in capitals as its prefix. TEMPLATE.md is exempt from the id and prefix
    rules: its id is a placeholder.
  - every requirement id is unique and is either tagged in a test (`req: BAR-03`, several ids comma-separated, anywhere in
    a comment or the note column of a `vectors.tsv` row), or marked `[gap: untested]` right after the id. A
    `[gap: unmet]` requirement needs no tag. A tag naming no requirement fails. Test files with no tag are listed as info,
    never as a failure; tooling tests and voxcmd goldens simply stay untagged.
  - `specs/gaps.md` equals what the `[gap: ...]` markers generate, even when there are no specs. `--write` regenerates it.
  - every `.plans/**/*.md` is checked against specs/schema/plan.yaml, but only warns (`warn:` lines, no failure): `.plans/`
    is local and wholly git-ignored, so the write-time hook (`--file`) and `just plan-new` enforce, not this step. Where
    it does not exist (CI, a worktree) there is nothing to check.

Validation is check-jsonschema's, which reads whole YAML files: the front matter is written to a temp file and the
tool run on it. The step fails, not skips, when check-jsonschema is not installed, so a machine without it cannot pass
a spec it never read (packages/pipx.ini installs it).

  python3 -B lib/check/steps/specs.py [--write]
  python3 -B lib/check/steps/specs.py --file <plan doc>   # exit 1 and print the findings for that one doc
"""

import glob
import os
import re
import shutil
import subprocess
import sys
import tempfile
from typing import NamedTuple

sys.dont_write_bytecode = True
REPO_DIR = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))

SPEC_SCHEMA = "specs/schema/spec.yaml"
PLAN_SCHEMA = "specs/schema/plan.yaml"
TEMPLATE = "TEMPLATE.md"
REQUIRED_HEADINGS = ("What it is for", "Requirements", "Not covered")
MISSING_TOOL = "check-jsonschema is not installed (pipx install check-jsonschema); the specs step fails without it rather than pass unread"

FRONT_MATTER = re.compile(r"\A---\n(.*?\n)?---[ \t]*(?:\n|\Z)", re.DOTALL)
# The id as YAML reads it: `id: bar`, `id: "bar"` and `id: 'bar'` are the same value.
TOP_LEVEL_ID = re.compile(r"""^id:[ \t]*(?:"([^"\n]*)"|'([^'\n]*)'|([^\s#]*))""", re.MULTILINE)
REQUIREMENT = re.compile(r"^- \*\*([A-Z]{2,})-\d{2,}\*\*")
# Gap markers sit right after the id so that prose mentioning one is not read as a marker.
GAP_LINE = re.compile(r"^- \*\*([A-Z]{2,}-\d{2,})\*\*[ \t]*(?:\[gap: (untested|unmet)\])?[ \t]*(.*)$")
REQUIREMENT_ID = r"[A-Z]{2,}-\d{2,}"
TAG = re.compile(rf"\breq: ({REQUIREMENT_ID}(?:, ?{REQUIREMENT_ID})*)\b")
# A tag counts only in a comment: after the file type's comment marker, outside a string literal, so a string that happens
# to hold a tag is not coverage. The marker follows the extension, since `--flag` and `http://` are code in other
# languages. A file of any other type is not scanned rather than guessed at. A .tsv takes a tag on a whole-line `#` comment
# or in its note column: the one the header row names `note`, else the fourth.
HASH_MARKERS = ("#",)
SLASH_MARKERS = ("//", "/*")
COMMENT_MARKERS_BY_EXTENSION = {
    ".py": HASH_MARKERS, ".sh": HASH_MARKERS, ".bash": HASH_MARKERS,
    ".js": SLASH_MARKERS, ".qml": SLASH_MARKERS, ".rs": SLASH_MARKERS,
    ".lua": ("--",),
}
SHELL_OR_PYTHON_SHEBANG = re.compile(r"\A#!.*\b(?:sh|bash|python3?)\b")
DEFAULT_TSV_NOTE_COLUMN = 3
QUOTES = "'\"`"
# Directories whose test files may carry tags. Docs are not scanned, so prose cannot be mistaken for a tag.
SCAN_ROOTS = (
    "lib/check/tests", "home/voxcmd/tests", "home/quickshell/tests", ".claude/skills/shadow", "home/hypr/tests",
    "home/calendar/tests", "home/voxtype/tests",
)
SKIPPED_DIRS = frozenset({".git", "node_modules", "target", "__pycache__"})
GAPS_FILE = "specs/gaps.md"
GAPS_HEADER = (
    "<!-- Generated by `python3 -B lib/check/steps/specs.py --write` from the [gap: ...] markers in specs/core/*.md. "
    "Do not edit. -->\n# Gaps\n\n"
)
FENCE = re.compile(r"^ {0,3}(```|~~~)")


def split_front_matter(text):
    """(front matter text, body text, number of lines before the body), or None without a leading `---` block."""
    match = FRONT_MATTER.match(text)
    if not match:
        return None
    return match.group(1) or "", text[match.end():], text[:match.end()].count("\n")


def body_lines(body):
    """(line within the body, line) for each line outside a fenced code block."""
    fenced = None
    for number, line in enumerate(body.splitlines(), 1):
        fence = FENCE.match(line)
        if fence and fenced in (None, fence.group(1)):
            fenced = None if fenced else fence.group(1)
        elif not fenced:
            yield number, line


def check_body(path, body, offset, spec_id, is_template):
    """Findings for a spec's body: title, headings and requirement prefixes."""
    findings = []
    lines = list(body_lines(body))
    headings = {line[3:].strip() for _, line in lines if line.startswith("## ")}
    if not any(line.startswith("# ") for _, line in lines):
        findings.append(f"{path}:{offset + 1}: no `# <title>` heading after the front matter")
    for heading in REQUIRED_HEADINGS:
        if heading not in headings:
            findings.append(f"{path}:{offset + 1}: missing the `## {heading}` heading")
    if is_template or not spec_id:
        return findings
    prefix = spec_id.upper()
    for number, line in lines:
        found = REQUIREMENT.match(line)
        if found and found.group(1) != prefix:
            findings.append(f"{path}:{offset + number}: requirement {found.group(1)}-.. does not start with {prefix}, the prefix of spec {spec_id}")
    return findings


class Requirement(NamedTuple):
    id: str
    path: str
    line: int
    gap: str  # "untested", "unmet" or ""
    text: str


def read_requirements(root):
    """Every requirement line of the specs under specs/core, TEMPLATE.md excluded, in file then line order."""
    found = []
    for full in sorted(glob.glob(os.path.join(root, "specs", "core", "*.md"))):
        path = os.path.relpath(full, root)
        if os.path.basename(path) == TEMPLATE:
            continue
        with open(full) as handle:
            parts = split_front_matter(handle.read())
        if parts is None:
            continue
        _, body, offset = parts
        for number, line in body_lines(body):
            match = GAP_LINE.match(line)
            if match:
                found.append(Requirement(match.group(1), path, offset + number, match.group(2) or "", match.group(3)))
    return found


def comment_start(line, markers):
    """Index where the line's comment begins, or None. Quotes are skipped with their backslash escapes. For the
    slash markers a leading `*` is a block comment's continuation line."""
    if markers is SLASH_MARKERS and line.lstrip().startswith("*"):
        return line.index("*")
    quote = None
    index = 0
    while index < len(line):
        char = line[index]
        if quote:
            if char == "\\":
                index += 1
            elif char == quote:
                quote = None
        elif char in QUOTES:
            quote = char
        elif line.startswith(markers, index):
            return index
        index += 1
    return None


def comment_markers(path, first_line):
    """The comment markers of a test file, or None for a type that is not scanned."""
    extension = os.path.splitext(path)[1]
    if extension:
        return COMMENT_MARKERS_BY_EXTENSION.get(extension)
    return HASH_MARKERS if SHELL_OR_PYTHON_SHEBANG.match(first_line) else None


def tsv_note_column(lines):
    """Index of the note column: where the first non-comment row, if a header, has a field `note`, else the default."""
    header = next((line.split("\t") for line in lines if not line.startswith("#")), [])
    return header.index("note") if "note" in header else DEFAULT_TSV_NOTE_COLUMN


def tags_in_line(line, markers, note_column=None):
    """The requirement ids tagged in a line of a test file; see COMMENT_MARKERS_BY_EXTENSION for where a tag counts.
    note_column is given for a .tsv."""
    if note_column is not None:
        fields = line.split("\t")
        scanned = line if line.startswith("#") else fields[note_column] if len(fields) > note_column else ""
    else:
        comment = comment_start(line, markers)
        scanned = "" if comment is None else line[comment:]
    return [tag for found in TAG.finditer(scanned) for tag in re.findall(REQUIREMENT_ID, found.group(1))]


def scan_tests(root):
    """((tag id, path, line) for each tag, paths of text files with no tag) over SCAN_ROOTS."""
    tags, untagged = [], []
    for scan_root in SCAN_ROOTS:
        for directory, subdirs, names in os.walk(os.path.join(root, scan_root)):
            subdirs[:] = sorted(name for name in subdirs if name not in SKIPPED_DIRS)
            for name in sorted(names):
                full = os.path.join(directory, name)
                path = os.path.relpath(full, root)
                if os.path.islink(full):
                    continue
                try:
                    with open(full, encoding="utf-8") as handle:
                        lines = handle.read().splitlines()
                except (UnicodeDecodeError, OSError):
                    continue
                is_tsv = path.endswith(".tsv")
                note_column = tsv_note_column(lines) if is_tsv else None
                markers = comment_markers(path, lines[0] if lines else "")
                if markers is None and not is_tsv:
                    continue
                before = len(tags)
                for number, line in enumerate(lines, 1):
                    tags.extend((tag, path, number) for tag in tags_in_line(line, markers, note_column))
                if len(tags) == before:
                    untagged.append(path)
    return tags, untagged


def check_links(root):
    """(findings, info lines) for requirement uniqueness, tags and gap markers."""
    findings, seen = [], {}
    requirements = read_requirements(root)
    for req in requirements:
        if req.id in seen:
            findings.append(f"{req.path}:{req.line}: requirement {req.id} repeats {seen[req.id].path}:{seen[req.id].line}; ids are never reused")
        else:
            seen[req.id] = req
    tags, untagged = scan_tests(root)
    tagged = {tag for tag, _, _ in tags}
    for tag, path, number in tags:
        if tag not in seen:
            findings.append(f"{path}:{number}: tag {tag} names no requirement in specs/core")
    for req in seen.values():
        if not req.gap and req.id not in tagged:
            findings.append(f"{req.path}:{req.line}: requirement {req.id} has no test tagged `req: {req.id}`; tag one or mark it [gap: untested]")
    info = []
    if requirements and untagged:
        info = [f"info: {len(untagged)} test files carry no requirement tag (allowed):", *(f"  {path}" for path in untagged)]
    return findings, info


def render_gaps(requirements):
    """The text of specs/gaps.md for the gap-marked requirements."""
    gaps = sorted((req for req in requirements if req.gap), key=lambda req: req.id)
    if not gaps:
        return GAPS_HEADER + "None.\n"
    lines = [f"- **{req.id}** ({req.gap}; [{os.path.basename(req.path)}]({os.path.relpath(req.path, 'specs')})) {req.text}".rstrip() for req in gaps]
    return GAPS_HEADER + "\n".join(lines) + "\n"


def check_gaps_file(root):
    path = os.path.join(root, GAPS_FILE)
    try:
        with open(path) as handle:
            current = handle.read()
    except FileNotFoundError:
        current = None
    if current == render_gaps(read_requirements(root)):
        return []
    return [f"{GAPS_FILE}:1: {'missing' if current is None else 'out of date'}; run `python3 -B lib/check/steps/specs.py --write`"]


def write_gaps(root):
    path = os.path.join(root, GAPS_FILE)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as handle:
        handle.write(render_gaps(read_requirements(root)))


def validate(root, schema, front_matters):
    """check-jsonschema findings for {path: front matter text}, with the temp file names turned back into the paths."""
    if not front_matters:
        return []
    with tempfile.TemporaryDirectory() as scratch:
        temp_to_path = {}
        for index, (path, text) in enumerate(sorted(front_matters.items())):
            temp = os.path.join(scratch, f"{index}.yaml")
            with open(temp, "w") as handle:
                handle.write(text)
            temp_to_path[temp] = path
        done = subprocess.run(
            ["check-jsonschema", "--schemafile", os.path.join(os.path.abspath(root), schema), *temp_to_path],
            capture_output=True, text=True, cwd=scratch,
        )
    if done.returncode == 0:
        return []
    output = done.stdout + done.stderr
    for temp, path in temp_to_path.items():
        output = output.replace(temp, path)
    lines = [line for line in output.splitlines() if line.strip() and not line.startswith("Schema validation errors were encountered")]
    return lines or ["schema validation failed"]


def check_specs(root):
    findings, front_matters = [], {}
    for full in sorted(glob.glob(os.path.join(root, "specs", "core", "*.md"))):
        path = os.path.relpath(full, root)
        with open(full) as handle:
            parts = split_front_matter(handle.read())
        if parts is None:
            findings.append(f"{path}:1: no front matter (a spec starts with a `---` block)")
            continue
        front, body, offset = parts
        front_matters[path] = front
        is_template = os.path.basename(path) == TEMPLATE
        found = TOP_LEVEL_ID.search(front)
        spec_id = next((group for group in found.groups() if group is not None), "") if found else ""
        stem = os.path.basename(path)[:-3]
        if not is_template and spec_id and spec_id != stem:
            findings.append(f"{path}:1: id {spec_id} is not the file name {stem}")
        findings.extend(check_body(path, body, offset, spec_id, is_template))
    return findings + validate(root, SPEC_SCHEMA, front_matters)


def plan_findings(root, full_paths, shown_from=None):
    """Findings for plan docs (absolute paths), shown relative to shown_from (default root): front matter present and
    valid against the schema in root."""
    shown_from = shown_from or root
    findings, front_matters = [], {}
    for full in full_paths:
        path = os.path.relpath(full, shown_from)
        try:
            with open(full, encoding="utf-8") as handle:
                parts = split_front_matter(handle.read())
        except (OSError, UnicodeError) as error:
            # A plan that cannot be read is a finding, not a crash: .plans docs only ever warn.
            findings.append(f"{path}: unreadable: {error}")
            continue
        if parts is None:
            findings.append(f"{path}:1: no front matter (a plan starts with a `---` block)")
        else:
            front_matters[path] = parts[0]
    return findings + validate(root, PLAN_SCHEMA, front_matters)


def check_plans(root):
    """Findings for every .plans doc. Callers report them as warnings: see the module docstring."""
    return plan_findings(root, sorted(glob.glob(os.path.join(root, ".plans", "**", "*.md"), recursive=True)))


def run_checks(root, info=None):
    """Every finding for the checkout at root; info, when given, is extended with the non-failing lines."""
    if not shutil.which("check-jsonschema"):
        return [MISSING_TOOL]
    links, notes = check_links(root)
    if info is not None:
        info.extend(notes)
    if info is not None:
        info.extend(f"warn: {finding}" for finding in check_plans(root))
    return check_specs(root) + links + check_gaps_file(root)


def check_one_plan(path):
    """Print the findings for one plan doc and return the exit code; this is the write-time hook's entry."""
    if not shutil.which("check-jsonschema"):
        print(MISSING_TOOL, file=sys.stderr)
        return 1
    try:
        findings = plan_findings(REPO_DIR, [os.path.abspath(path)], os.getcwd())
    except OSError as error:
        findings = [f"{path}: {error.strerror or error}"]
    for finding in findings:
        print(finding, file=sys.stderr)
    return 1 if findings else 0


def main(argv):
    if len(argv) == 2 and argv[0] == "--file":
        return check_one_plan(argv[1])
    if argv not in ([], ["--write"]):
        print("usage: lib/check/steps/specs.py [--write | --file <plan doc>]", file=sys.stderr)
        return 2
    if argv:
        write_gaps(REPO_DIR)
    info = []
    findings = run_checks(REPO_DIR, info)
    for line in info:
        print(line)
    for finding in findings:
        print(finding, file=sys.stderr)
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
