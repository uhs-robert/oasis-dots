#!/usr/bin/env python3
"""Writes the board's dark theme blocks into board.html from the Oasis CSS themes.

Usage: gen_board_themes.py [--check] [OASIS_DIR]

OASIS_DIR is a checkout of oasis.nvim (default: repos/oasis.nvim of this dotfiles checkout, or its main checkout when
run from a worktree). With --check the script rewrites nothing and exits 1 when board.html is stale.
"""

import colorsys
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BOARD = os.path.join(HERE, "plans", "board.html")
# The markers in board.html carry no text of their own; the generator writes the "generated" notice after the start.
CSS_START, CSS_END = "/* themes:start", "/* themes:end */"
JS_START, JS_END = "// themes:start", "// themes:end"
NOTICE = "generated by gen_board_themes.py, do not edit"
MIN_CONTRAST = 4.5
# The same-hue search stays in a 25 degree hue window so an accent keeps its identity, and under this lightness so a
# near-white tint of the hue (palette 50 steps) is not taken: it reads as plain text and sits next to --text.
MAX_LIGHTNESS = 0.85

# Board role -> Oasis var. --dim is syntax-bracket, not fg-dim: fg-dim is under 4.5:1 on cards.
ROLES = {
    "bg": "bg-core", "panel": "bg-mantle", "card": "bg-surface", "line": "ui-visual-bg", "text": "fg-core",
    "dim": "syntax-bracket", "accent": "theme-primary", "warn": "git-change", "bad": "git-delete", "good": "git-add",
    "error-bg": "ui-diag-error-bg",
    "assignee-orange": "terminal-bright-yellow", "assignee-teal": "terminal-cyan", "assignee-sky": "terminal-bright-blue",
    "assignee-iris": "syntax-builtin-const", "assignee-magenta": "terminal-magenta",
}


def luminance(hex_color):
    channels = [int(hex_color[index:index + 2], 16) / 255 for index in (1, 3, 5)]
    linear = [value / 12.92 if value <= 0.03928 else ((value + 0.055) / 1.055) ** 2.4 for value in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(foreground, background):
    high, low = sorted((luminance(foreground), luminance(background)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def read_vars(path):
    with open(path, encoding="utf-8") as handle:
        return dict(re.findall(r"--oasis-([\w-]+):\s*([^;]+);", handle.read()))


def is_hex(color):
    return re.fullmatch(r"#[0-9A-Fa-f]{6}", color) is not None


def hls_of(hex_color):
    return colorsys.rgb_to_hls(*(int(hex_color[index:index + 2], 16) / 255 for index in (1, 3, 5)))


def hue_of(hex_color):
    return hls_of(hex_color)[0] * 360


def hue_distance(first, second):
    gap = abs(hue_of(first) - hue_of(second)) % 360
    return min(gap, 360 - gap)


def lighter_neutral(values, current, card=None, below=None):
    """The closest lighter neutral of the same theme, else None. With a card it must reach the contrast floor too, and
    with `below` it must be darker than that color (a dim gray must stay under the text). Candidates are sorted so a luminance tie picks the same color every run."""
    neutrals = {values[key].upper() for key in values
                if (key.startswith("fg-") or key == "syntax-bracket") and is_hex(values[key])}
    passing = sorted(color for color in neutrals if luminance(color) > luminance(current) and (below is None or luminance(color) < luminance(below))
                     and (card is None or contrast(color, card) >= MIN_CONTRAST))
    return min(passing, key=luminance) if passing else None


def lighter_same_hue(values, current, card):
    """The closest lighter color of the theme within 25 degrees of `current` (grays have no hue, so they do not count) that reaches the floor on the card, or None."""
    colors = {value.upper() for value in values.values() if is_hex(value)}
    passing = sorted(color for color in colors if luminance(color) > luminance(current)
                     and hls_of(color)[2] >= 0.3 and hls_of(color)[1] <= MAX_LIGHTNESS
                     and hue_distance(color, current) <= 25 and contrast(color, card) >= MIN_CONTRAST)
    return min(passing, key=luminance) if passing else None


def theme_roles(values, notes):
    """The board roles of one theme. Each adjustment is a line in `notes`, for the generator to print."""
    name = values["name"].strip('"')
    roles = {role: values[var].upper() for role, var in ROLES.items()}
    if contrast(roles["dim"], roles["card"]) < MIN_CONTRAST:
        found = lighter_neutral(values, roles["dim"], roles["card"], below=roles["text"])
        if found:
            roles["dim"] = found
            notes.append(f"{name}: dim raised to {found} for contrast")
        else:
            notes.append(f"{name}: dim stays {roles['dim']}, {contrast(roles['dim'], roles['card']):.2f}:1 on card, no neutral between it and the text color")
    # A border the same color as the card, or as the error background, disappears there.
    if roles["line"] in (roles["card"], roles["error-bg"]):
        roles["line"] = lighter_neutral(values, roles["line"]) or values["fg-core"].upper()
        notes.append(f"{name}: line matched the card or error background, now {roles['line']}")
    for role in ROLES:
        if not role.startswith("assignee-") or contrast(roles[role], roles["card"]) >= MIN_CONTRAST:
            continue
        found = lighter_same_hue(values, roles[role], roles["card"])
        if found:
            notes.append(f"{name}: {role} raised from {roles[role]} to {found}")
            roles[role] = found
        else:
            notes.append(f"{name}: {role} stays {roles[role]}, {contrast(roles[role], roles['card']):.2f}:1 on card, no lighter color of its hue")
    shadow = values["bg-shadow"]
    red, green, blue = (int(shadow[index:index + 2], 16) for index in (1, 3, 5))
    roles["overlay"] = f"rgba({red}, {green}, {blue}, 0.6)"
    return roles


def load_themes(oasis_dir, notes):
    folder = os.path.join(oasis_dir, "extras", "css", "themes", "dark")
    themes = []
    for name in sorted(os.listdir(folder)):
        match = re.fullmatch(r"oasis_(\w+)_dark\.css", name)
        if not match:
            continue
        values = read_vars(os.path.join(folder, name))
        label = match.group(1).capitalize()
        themes.append((f"{match.group(1)}_dark", label, theme_roles(values, notes)))
    return themes


def css_block(themes):
    lines = [f"{CSS_START} ({NOTICE}) */"]
    for key, _label, roles in themes:
        body = "; ".join(f"--{role}: {value}" for role, value in roles.items())
        lines.append(f'  html[data-theme="{key}"] {{ {body}; }}')
    lines.append("  " + CSS_END)
    return "\n".join(lines)


def js_block(themes):
    entries = ",\n".join(f'  ["{key}", "{label}"]' for key, label, _roles in themes)
    return f"{JS_START} ({NOTICE})\nconst THEMES = [\n{entries},\n];\n{JS_END}"


def replace_between(text, start, end, block):
    pattern = re.compile(rf"[ \t]*{re.escape(start)}.*?^[ \t]*{re.escape(end)}", re.S | re.M)
    if not pattern.search(text):
        raise SystemExit(f"board.html has no {start!r} block")
    indent = re.search(rf"([ \t]*){re.escape(start)}", text).group(1)
    block = "\n".join(indent + line.lstrip() if index == 0 else line for index, line in enumerate(block.split("\n")))
    return pattern.sub(lambda _match: block, text, count=1)


def generate(oasis_dir, text, notes=None):
    themes = load_themes(oasis_dir, [] if notes is None else notes)
    text = replace_between(text, CSS_START, CSS_END, css_block(themes))
    return replace_between(text, JS_START, JS_END, js_block(themes))


def default_oasis_dir():
    common = subprocess.run(["git", "-C", HERE, "rev-parse", "--path-format=absolute", "--git-common-dir"],
                            capture_output=True, text=True, check=False).stdout.strip()
    for root in (os.path.join(HERE, *[".."] * 4), os.path.dirname(common) if common else ""):
        candidate = os.path.join(root, "repos", "oasis.nvim")
        if os.path.isdir(candidate):
            return os.path.normpath(candidate)
    return os.path.join(HERE, *[".."] * 4, "repos", "oasis.nvim")


def main(argv):
    check = "--check" in argv
    paths = [arg for arg in argv if not arg.startswith("--")]
    oasis_dir = paths[0] if paths else default_oasis_dir()
    with open(BOARD, encoding="utf-8") as handle:
        current = handle.read()
    notes = []
    fresh = generate(oasis_dir, current, notes)
    for note in notes:
        print(note)
    if check:
        return 0 if fresh == current else 1
    with open(BOARD, "w", encoding="utf-8") as handle:
        handle.write(fresh)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
