// A 9x9 moon lit by `phase` (0 new, 0.5 full): 1 lit, 8 shadow.
function moon(phase) {
    var theta = 2 * Math.PI * phase;
    var edge = Math.cos(theta);
    var rows = [];
    for (var y = 0; y < 9; y++) {
        var row = "";
        for (var x = 0; x < 9; x++) {
            var nx = (x - 4) / 4.4;
            var ny = (y - 4) / 4.4;
            if (nx * nx + ny * ny > 1) {
                row += ".";
                continue;
            }
            var px = nx / Math.sqrt(Math.max(0.0001, 1 - ny * ny));
            var lit = phase <= 0.5 ? px >= edge : px <= -edge;
            row += lit ? "1" : "8";
        }
        rows.push(row);
    }
    return rows;
}
